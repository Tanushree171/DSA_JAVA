package Basic01;

public class CharDataType {
    static void main() {
        //typecasting is converting one data type into another data type
        char ch = 'A'; // single commas only one alphabet or character is used
      int x = ch; //  implicit typecasting
        System.out.println(x);
char jay = '$';
int y = (int)jay; // explicit typecasting
        System.out.println(y);
        //ASCII Values a- 97 and further goes on till z-122, A-66 further goes till Z-90, 0-48 further goes till 9-57
char sy ='c';
        System.out.println(sy*sy);// space character value is 32
    }
}
